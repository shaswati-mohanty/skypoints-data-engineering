-- Snowflake reference schema. Use transient/temporary staging where replay policy permits.
CREATE SCHEMA IF NOT EXISTS SKYPOINTS;
-- Select the intended database before applying this file, or fully qualify every object.
-- Re-evaluate clustering keys with production query profiles; automatic clustering has a cost.
CREATE TABLE IF NOT EXISTS SKYPOINTS.MEMBER_LANDING (
  BATCH_ID VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL, SOURCE_ROW_NUMBER NUMBER NOT NULL,
  INGESTED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  SOURCE_UPDATED_AT TIMESTAMP_NTZ, RAW_RECORD VARIANT NOT NULL,
  RECORD_TYPE VARCHAR, MEMBER_NAME VARCHAR, MEMBER_ID VARCHAR, ENROLLMENT_DATE_RAW VARCHAR,
  LAST_FLIGHT_DATE_RAW VARCHAR, TIER_CODE VARCHAR, AGENT_NAME VARCHAR, STATE VARCHAR,
  COUNTRY VARCHAR, POSTCODE_RAW VARCHAR, DOB_RAW VARCHAR, IS_ACTIVE VARCHAR,
  CONSTRAINT PK_MEMBER_LANDING PRIMARY KEY (BATCH_ID, SOURCE_FILE, SOURCE_ROW_NUMBER) NOT ENFORCED
) CLUSTER BY (BATCH_ID, COUNTRY);
CREATE TABLE IF NOT EXISTS SKYPOINTS.MEMBER_STAGING (
  MEMBER_ID VARCHAR(18) NOT NULL, MEMBER_NAME VARCHAR(255) NOT NULL,
  ENROLLMENT_DATE DATE NOT NULL, LAST_FLIGHT_DATE DATE, TIER_CODE CHAR(5), AGENT_NAME VARCHAR(255),
  STATE CHAR(5), COUNTRY CHAR(5) NOT NULL, POSTCODE NUMBER(5,0), DOB DATE, IS_ACTIVE CHAR(1),
  AGE NUMBER(3,0), STALE_MEMBER BOOLEAN NOT NULL, SOURCE_UPDATED_AT TIMESTAMP_NTZ NOT NULL,
  BATCH_ID VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL, SOURCE_ROW_NUMBER NUMBER NOT NULL,
  CONSTRAINT PK_MEMBER_STAGING PRIMARY KEY (MEMBER_ID, SOURCE_UPDATED_AT, SOURCE_FILE, SOURCE_ROW_NUMBER) NOT ENFORCED
) CLUSTER BY (COUNTRY, MEMBER_ID);
CREATE TABLE IF NOT EXISTS SKYPOINTS.MEMBER_CURRENT (
  MEMBER_ID VARCHAR(18) NOT NULL, MEMBER_NAME VARCHAR(255) NOT NULL, ENROLLMENT_DATE DATE NOT NULL,
  LAST_FLIGHT_DATE DATE, TIER_CODE CHAR(5), AGENT_NAME VARCHAR(255), STATE CHAR(5), COUNTRY CHAR(5) NOT NULL,
  POSTCODE NUMBER(5,0), DOB DATE, IS_ACTIVE CHAR(1), AGE NUMBER(3,0), STALE_MEMBER BOOLEAN NOT NULL,
  SOURCE_UPDATED_AT TIMESTAMP_NTZ NOT NULL, BATCH_ID VARCHAR NOT NULL,
  CONSTRAINT PK_MEMBER_CURRENT PRIMARY KEY (MEMBER_ID) NOT ENFORCED
);
-- Serving view can be replaced with per-country tables if physical separation is a firm requirement.
CREATE TABLE IF NOT EXISTS SKYPOINTS.REDEMPTION_LANDING (
  BATCH_ID VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL, INGESTED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  SOURCE_UPDATED_AT TIMESTAMP_NTZ, RAW_PAYLOAD VARIANT NOT NULL
);
CREATE TABLE IF NOT EXISTS SKYPOINTS.REDEMPTION_TRANSACTION (
  TXN_ID VARCHAR NOT NULL, MEMBER_ID VARCHAR(18) NOT NULL, FEED_DATE DATE NOT NULL,
  TXN_DATE DATE NOT NULL, PARTNER VARCHAR NOT NULL, MILES_REDEEMED NUMBER(18,0) NOT NULL,
  STATUS VARCHAR NOT NULL, BATCH_ID VARCHAR NOT NULL, SOURCE_UPDATED_AT TIMESTAMP_NTZ NOT NULL,
  INGESTED_AT TIMESTAMP_NTZ NOT NULL,
  CONSTRAINT PK_REDEMPTION_TRANSACTION PRIMARY KEY (TXN_ID) NOT ENFORCED
) CLUSTER BY (TXN_DATE, MEMBER_ID);
CREATE TABLE IF NOT EXISTS SKYPOINTS.DQ_REJECT (
  BATCH_ID VARCHAR NOT NULL, FEED_NAME VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL,
  SOURCE_ROW_NUMBER NUMBER, REASON_CODE VARCHAR NOT NULL, REASON_DETAIL VARCHAR,
  RAW_RECORD VARIANT, REJECTED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);
-- Country target template. Clone per canonical country code, e.g. MEMBER_INDIA.
CREATE TABLE IF NOT EXISTS SKYPOINTS.MEMBER_INDIA LIKE SKYPOINTS.MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS SKYPOINTS.MEMBER_USA LIKE SKYPOINTS.MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS SKYPOINTS.MEMBER_AUS LIKE SKYPOINTS.MEMBER_CURRENT;

CREATE TABLE IF NOT EXISTS SKYPOINTS.ETL_BATCH_AUDIT (
  BATCH_ID VARCHAR NOT NULL, FEED_NAME VARCHAR NOT NULL, SOURCE_URI VARCHAR NOT NULL,
  CONTENT_SHA256 VARCHAR(64) NOT NULL, INGEST_DATE DATE NOT NULL, STATUS VARCHAR NOT NULL,
  SOURCE_FILE_COUNT NUMBER NOT NULL,
  STARTED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(), COMPLETED_AT TIMESTAMP_NTZ,
  ROWS_READ NUMBER, ROWS_ACCEPTED NUMBER, ROWS_REJECTED NUMBER, ERROR_DETAIL VARCHAR,
  CONSTRAINT PK_ETL_BATCH_AUDIT PRIMARY KEY (BATCH_ID) NOT ENFORCED
);
