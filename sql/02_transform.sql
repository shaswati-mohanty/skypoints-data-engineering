-- Set BATCH_ID to an immutable, content-hash-based batch key before running.
-- AS_OF_DATE must be stable for a replay; source effective timestamps determine CDC order.
SET BATCH_ID = 'REPLACE_WITH_CONTENT_HASH';
SET AS_OF_DATE = CURRENT_DATE();

CREATE OR REPLACE TEMP FUNCTION PARSE_SOURCE_DATE(v VARCHAR)
RETURNS DATE
AS
$$
  COALESCE(
    TRY_TO_DATE(NULLIF(TRIM(v), ''), 'YYYYMMDD'),
    TRY_TO_DATE(NULLIF(TRIM(v), ''), 'MMDDYYYY'),
    TRY_TO_DATE(NULLIF(TRIM(v), ''), 'YYYY-MM-DD'),
    TRY_TO_DATE(NULLIF(TRIM(v), ''), 'MM/DD/YYYY'),
    IFF(REGEXP_LIKE(NULLIF(TRIM(v), ''), '^[0-9]{7}$'),
      COALESCE(
        TRY_TO_DATE(LPAD(SUBSTR(TRIM(v),1,1),2,'0') || SUBSTR(TRIM(v),2,2) || SUBSTR(TRIM(v),4,4), 'MMDDYYYY'),
        TRY_TO_DATE(SUBSTR(TRIM(v),1,2) || LPAD(SUBSTR(TRIM(v),3,1),2,'0') || SUBSTR(TRIM(v),4,4), 'MMDDYYYY')
      ), NULL)
  )
$$;

CREATE OR REPLACE TEMP TABLE MEMBER_PARSED AS
SELECT l.*,
       CASE UPPER(TRIM(COUNTRY))
         WHEN 'US' THEN 'USA' WHEN 'IN' THEN 'IND' WHEN 'AU' THEN 'AUS'
         ELSE UPPER(TRIM(COUNTRY))
       END AS COUNTRY_CANONICAL,
       PARSE_SOURCE_DATE(ENROLLMENT_DATE_RAW) AS ENROLLMENT_DATE_PARSED,
       PARSE_SOURCE_DATE(LAST_FLIGHT_DATE_RAW) AS FLIGHT_DATE_PARSED,
       PARSE_SOURCE_DATE(DOB_RAW) AS DOB_PARSED,
       COALESCE(SOURCE_UPDATED_AT, INGESTED_AT) AS EFFECTIVE_AT
FROM SKYPOINTS.MEMBER_LANDING l
WHERE BATCH_ID = $BATCH_ID AND RECORD_TYPE = 'D';

MERGE INTO SKYPOINTS.ETL_BATCH_AUDIT t
USING (
  SELECT $BATCH_ID AS BATCH_ID, 'MEMBER_AND_REDEMPTION' AS FEED_NAME,
         'SNOWFLAKE_LANDING' AS SOURCE_URI, $BATCH_ID AS CONTENT_SHA256,
         TO_DATE($AS_OF_DATE) AS INGEST_DATE, 2 AS SOURCE_FILE_COUNT,
         (SELECT COUNT(*) FROM SKYPOINTS.MEMBER_LANDING WHERE BATCH_ID=$BATCH_ID)
           + (SELECT COUNT(*) FROM SKYPOINTS.REDEMPTION_LANDING WHERE BATCH_ID=$BATCH_ID) AS ROWS_READ
) s ON t.BATCH_ID=s.BATCH_ID
WHEN MATCHED THEN UPDATE SET STATUS='RUNNING', FEED_NAME=s.FEED_NAME,
  SOURCE_URI=s.SOURCE_URI, CONTENT_SHA256=s.CONTENT_SHA256, INGEST_DATE=s.INGEST_DATE,
  SOURCE_FILE_COUNT=s.SOURCE_FILE_COUNT, ROWS_READ=s.ROWS_READ,
  COMPLETED_AT=NULL, ERROR_DETAIL=NULL, STARTED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
  (BATCH_ID,FEED_NAME,SOURCE_URI,CONTENT_SHA256,INGEST_DATE,STATUS,SOURCE_FILE_COUNT,ROWS_READ,STARTED_AT)
VALUES
  (s.BATCH_ID,s.FEED_NAME,s.SOURCE_URI,s.CONTENT_SHA256,s.INGEST_DATE,'RUNNING',
   s.SOURCE_FILE_COUNT,s.ROWS_READ,CURRENT_TIMESTAMP());

-- Row-level quarantine. DOB and flight date are optional; malformed non-null values are not.
INSERT INTO SKYPOINTS.DQ_REJECT
  (BATCH_ID, FEED_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER, REASON_CODE,
   REASON_DETAIL, RAW_RECORD)
SELECT BATCH_ID, 'MEMBER', SOURCE_FILE, SOURCE_ROW_NUMBER, 'INVALID_MEMBER_ROW',
       CASE
         WHEN MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '' THEN 'missing MEMBER_ID'
         WHEN LENGTH(MEMBER_ID) > 18 THEN 'MEMBER_ID exceeds 18 characters'
         WHEN MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '' THEN 'missing MEMBER_NAME'
         WHEN LENGTH(MEMBER_NAME) > 255 THEN 'MEMBER_NAME exceeds 255 characters'
         WHEN AGENT_NAME IS NOT NULL AND LENGTH(AGENT_NAME) > 255 THEN 'AGENT_NAME exceeds 255 characters'
         WHEN STATE IS NOT NULL AND LENGTH(STATE) > 5 THEN 'STATE exceeds 5 characters'
          WHEN COUNTRY_CANONICAL IS NULL OR COUNTRY_CANONICAL = '' THEN 'missing COUNTRY'
         WHEN ENROLLMENT_DATE_PARSED IS NULL THEN 'invalid or missing ENROLLMENT_DATE'
         WHEN DOB_RAW IS NOT NULL AND TRIM(DOB_RAW) <> '' AND DOB_PARSED IS NULL THEN 'invalid DOB'
         WHEN LAST_FLIGHT_DATE_RAW IS NOT NULL AND TRIM(LAST_FLIGHT_DATE_RAW) <> '' AND FLIGHT_DATE_PARSED IS NULL THEN 'invalid FLIGHT_DATE'
          WHEN COUNTRY_CANONICAL NOT IN ('USA','IND','AUS') THEN 'country is not in the approved target catalog'
         WHEN DOB_PARSED > $AS_OF_DATE THEN 'DOB is in the future'
         WHEN ENROLLMENT_DATE_PARSED > $AS_OF_DATE THEN 'ENROLLMENT_DATE is in the future'
         WHEN FLIGHT_DATE_PARSED > $AS_OF_DATE THEN 'FLIGHT_DATE is in the future'
         WHEN DOB_PARSED > ENROLLMENT_DATE_PARSED THEN 'DOB is after ENROLLMENT_DATE'
         WHEN NULLIF(TRIM(TIER_CODE),'') IS NOT NULL AND UPPER(TIER_CODE) NOT IN ('PLT','SLV','GLD') THEN 'invalid TIER_CODE'
         WHEN NULLIF(TRIM(IS_ACTIVE),'') IS NOT NULL AND UPPER(IS_ACTIVE) NOT IN ('A','I','Y','N','1','0') THEN 'invalid IS_ACTIVE'
         WHEN NULLIF(TRIM(POSTCODE_RAW),'') IS NOT NULL AND (TRY_TO_NUMBER(POSTCODE_RAW) IS NULL OR TRY_TO_NUMBER(POSTCODE_RAW) < 0 OR TRY_TO_NUMBER(POSTCODE_RAW) > 99999) THEN 'invalid POSTCODE'
       END,
       RAW_RECORD
FROM MEMBER_PARSED
WHERE (MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = ''
   OR MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = ''
   OR COUNTRY_CANONICAL IS NULL OR COUNTRY_CANONICAL = ''
   OR ENROLLMENT_DATE_PARSED IS NULL
   OR (DOB_RAW IS NOT NULL AND TRIM(DOB_RAW) <> '' AND DOB_PARSED IS NULL)
   OR (LAST_FLIGHT_DATE_RAW IS NOT NULL AND TRIM(LAST_FLIGHT_DATE_RAW) <> '' AND FLIGHT_DATE_PARSED IS NULL)
   OR COUNTRY_CANONICAL NOT IN ('USA','IND','AUS')
   OR DOB_PARSED > $AS_OF_DATE OR ENROLLMENT_DATE_PARSED > $AS_OF_DATE
   OR FLIGHT_DATE_PARSED > $AS_OF_DATE OR DOB_PARSED > ENROLLMENT_DATE_PARSED
   OR LENGTH(MEMBER_ID) > 18 OR LENGTH(MEMBER_NAME) > 255
   OR (AGENT_NAME IS NOT NULL AND LENGTH(AGENT_NAME) > 255)
   OR (STATE IS NOT NULL AND LENGTH(STATE) > 5)
   OR (NULLIF(TRIM(TIER_CODE),'') IS NOT NULL AND UPPER(TIER_CODE) NOT IN ('PLT','SLV','GLD'))
   OR (NULLIF(TRIM(IS_ACTIVE),'') IS NOT NULL AND UPPER(IS_ACTIVE) NOT IN ('A','I','Y','N','1','0'))
   OR (NULLIF(TRIM(POSTCODE_RAW),'') IS NOT NULL AND (TRY_TO_NUMBER(POSTCODE_RAW) IS NULL OR TRY_TO_NUMBER(POSTCODE_RAW) < 0 OR TRY_TO_NUMBER(POSTCODE_RAW) > 99999)))
  AND NOT EXISTS (
    SELECT 1 FROM SKYPOINTS.DQ_REJECT d
    WHERE d.BATCH_ID = MEMBER_PARSED.BATCH_ID
      AND d.SOURCE_FILE = MEMBER_PARSED.SOURCE_FILE
      AND d.SOURCE_ROW_NUMBER = MEMBER_PARSED.SOURCE_ROW_NUMBER
      AND d.FEED_NAME = 'MEMBER'
      AND d.REASON_CODE = 'INVALID_MEMBER_ROW'
  );

-- Build one winner per stable global member ID. Source timestamps must come from the source system.
CREATE OR REPLACE TEMP TABLE MEMBER_WINNERS AS
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE_PARSED AS ENROLLMENT_DATE,
       FLIGHT_DATE_PARSED AS LAST_FLIGHT_DATE, NULLIF(UPPER(TRIM(TIER_CODE)),'') AS TIER_CODE, AGENT_NAME, STATE,
        COUNTRY_CANONICAL AS COUNTRY, TRY_TO_NUMBER(POSTCODE_RAW) AS POSTCODE, DOB_PARSED AS DOB,
       NULLIF(UPPER(TRIM(IS_ACTIVE)),'') AS IS_ACTIVE,
       IFF(DOB_PARSED IS NULL, NULL,
           DATEDIFF(year, DOB_PARSED, $AS_OF_DATE)
             - IFF(TO_CHAR($AS_OF_DATE, 'MMDD') < TO_CHAR(DOB_PARSED, 'MMDD'), 1, 0)) AS AGE,
       COALESCE(DATEDIFF(day, FLIGHT_DATE_PARSED, $AS_OF_DATE) > 90, FALSE) AS STALE_MEMBER,
       EFFECTIVE_AT AS SOURCE_UPDATED_AT, BATCH_ID, SOURCE_FILE, SOURCE_ROW_NUMBER
FROM MEMBER_PARSED
WHERE MEMBER_ID IS NOT NULL AND TRIM(MEMBER_ID) <> ''
  AND MEMBER_NAME IS NOT NULL AND TRIM(MEMBER_NAME) <> ''
  AND LENGTH(MEMBER_ID) <= 18 AND LENGTH(MEMBER_NAME) <= 255
  AND (AGENT_NAME IS NULL OR LENGTH(AGENT_NAME) <= 255)
  AND (STATE IS NULL OR LENGTH(STATE) <= 5)
  AND COUNTRY_CANONICAL IN ('USA','IND','AUS') AND ENROLLMENT_DATE_PARSED IS NOT NULL
  AND (NULLIF(TRIM(TIER_CODE),'') IS NULL OR UPPER(TIER_CODE) IN ('PLT','SLV','GLD'))
  AND (NULLIF(TRIM(IS_ACTIVE),'') IS NULL OR UPPER(IS_ACTIVE) IN ('A','I','Y','N','1','0'))
  AND (NULLIF(TRIM(POSTCODE_RAW),'') IS NULL OR TRY_TO_NUMBER(POSTCODE_RAW) BETWEEN 0 AND 99999)
  AND (DOB_RAW IS NULL OR TRIM(DOB_RAW) = '' OR DOB_PARSED IS NOT NULL)
  AND (LAST_FLIGHT_DATE_RAW IS NULL OR TRIM(LAST_FLIGHT_DATE_RAW) = '' OR FLIGHT_DATE_PARSED IS NOT NULL)
  AND COALESCE(DOB_PARSED <= $AS_OF_DATE, TRUE)
  AND ENROLLMENT_DATE_PARSED <= $AS_OF_DATE
  AND COALESCE(FLIGHT_DATE_PARSED <= $AS_OF_DATE, TRUE)
  AND COALESCE(DOB_PARSED <= ENROLLMENT_DATE_PARSED, TRUE)
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY MEMBER_ID
  ORDER BY EFFECTIVE_AT DESC, BATCH_ID DESC, SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC
) = 1;

-- Log superseded same-batch member rows so deduplication is auditable.
INSERT INTO SKYPOINTS.DQ_REJECT
  (BATCH_ID, FEED_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER, REASON_CODE, REASON_DETAIL, RAW_RECORD)
SELECT BATCH_ID, 'MEMBER', SOURCE_FILE, SOURCE_ROW_NUMBER, 'DUPLICATE_MEMBER_SUPERSEDED',
       'A later source record for this member won the batch', RAW_RECORD
FROM MEMBER_PARSED
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY MEMBER_ID
  ORDER BY EFFECTIVE_AT DESC, BATCH_ID DESC, SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC
) > 1
  AND NOT EXISTS (
    SELECT 1 FROM SKYPOINTS.DQ_REJECT d
    WHERE d.BATCH_ID = MEMBER_PARSED.BATCH_ID
      AND d.SOURCE_FILE = MEMBER_PARSED.SOURCE_FILE
      AND d.SOURCE_ROW_NUMBER = MEMBER_PARSED.SOURCE_ROW_NUMBER
      AND d.FEED_NAME = 'MEMBER'
      AND d.REASON_CODE = 'DUPLICATE_MEMBER_SUPERSEDED'
  );

CREATE OR REPLACE TEMP TABLE REDEMPTION_PARSED AS
SELECT l.BATCH_ID, l.SOURCE_FILE, l.INGESTED_AT,
       COALESCE(l.SOURCE_UPDATED_AT, l.INGESTED_AT) AS EFFECTIVE_AT,
       COALESCE(feed.index::NUMBER, 0) * 1000000 + COALESCE(txn.index::NUMBER, 0) AS SOURCE_ROW_NUMBER,
       feed.value:member_id::VARCHAR AS MEMBER_ID,
       PARSE_SOURCE_DATE(feed.value:feed_date::VARCHAR) AS FEED_DATE,
       txn.value:txn_id::VARCHAR AS TXN_ID,
       PARSE_SOURCE_DATE(txn.value:txn_date::VARCHAR) AS TXN_DATE,
       txn.value:partner::VARCHAR AS PARTNER,
       TRY_TO_NUMBER(txn.value:miles_redeemed::VARCHAR) AS MILES_REDEEMED,
       UPPER(txn.value:status::VARCHAR) AS STATUS,
       txn.value AS RAW_TXN
FROM SKYPOINTS.REDEMPTION_LANDING l,
     LATERAL FLATTEN(INPUT => IFF(IS_ARRAY(l.RAW_PAYLOAD), l.RAW_PAYLOAD, ARRAY_CONSTRUCT(l.RAW_PAYLOAD))) feed,
     LATERAL FLATTEN(INPUT => feed.value:redemptions) txn
WHERE l.BATCH_ID = $BATCH_ID;

INSERT INTO SKYPOINTS.DQ_REJECT
  (BATCH_ID, FEED_NAME, SOURCE_FILE, REASON_CODE, REASON_DETAIL, RAW_RECORD)
SELECT l.BATCH_ID, 'REDEMPTION', l.SOURCE_FILE, 'INVALID_REDEMPTION_FEED',
       'Expected an object/array feed with member_id, feed_date, and redemptions array', l.RAW_PAYLOAD
FROM SKYPOINTS.REDEMPTION_LANDING l,
     LATERAL FLATTEN(INPUT => IFF(IS_ARRAY(l.RAW_PAYLOAD), l.RAW_PAYLOAD, ARRAY_CONSTRUCT(l.RAW_PAYLOAD))) feed
WHERE l.BATCH_ID = $BATCH_ID
  AND (TYPEOF(feed.value) <> 'OBJECT' OR feed.value:member_id IS NULL
       OR PARSE_SOURCE_DATE(feed.value:feed_date::VARCHAR) IS NULL
       OR NOT IS_ARRAY(feed.value:redemptions))
  AND NOT EXISTS (
    SELECT 1 FROM SKYPOINTS.DQ_REJECT d
    WHERE d.BATCH_ID=l.BATCH_ID AND d.SOURCE_FILE=l.SOURCE_FILE
      AND d.FEED_NAME='REDEMPTION' AND d.REASON_CODE='INVALID_REDEMPTION_FEED'
  );

INSERT INTO SKYPOINTS.DQ_REJECT
  (BATCH_ID, FEED_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER, REASON_CODE, REASON_DETAIL, RAW_RECORD)
SELECT BATCH_ID, 'REDEMPTION', SOURCE_FILE, SOURCE_ROW_NUMBER, 'INVALID_REDEMPTION',
       CASE
         WHEN MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '' THEN 'missing member_id'
         WHEN FEED_DATE IS NULL THEN 'invalid feed_date'
         WHEN TXN_ID IS NULL OR TRIM(TXN_ID) = '' THEN 'missing txn_id'
         WHEN TXN_DATE IS NULL THEN 'invalid txn_date'
         WHEN PARTNER IS NULL OR TRIM(PARTNER) = '' THEN 'missing partner'
         WHEN MILES_REDEEMED IS NULL OR MILES_REDEEMED <= 0 OR MILES_REDEEMED <> TRUNC(MILES_REDEEMED) THEN 'miles_redeemed must be a positive integer'
         WHEN STATUS IS NULL OR STATUS NOT IN ('COMPLETED','PENDING','REJECTED','CANCELLED') THEN 'unknown status'
         ELSE 'transaction date exceeds feed date'
       END,
       RAW_TXN
FROM REDEMPTION_PARSED
WHERE (MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '' OR FEED_DATE IS NULL
   OR TXN_ID IS NULL OR TRIM(TXN_ID) = '' OR TXN_DATE IS NULL
   OR PARTNER IS NULL OR TRIM(PARTNER) = '' OR MILES_REDEEMED IS NULL OR MILES_REDEEMED <= 0
   OR MILES_REDEEMED <> TRUNC(MILES_REDEEMED)
   OR STATUS IS NULL OR STATUS NOT IN ('COMPLETED','PENDING','REJECTED','CANCELLED')
   OR FEED_DATE > $AS_OF_DATE OR TXN_DATE > $AS_OF_DATE OR TXN_DATE > FEED_DATE)
  AND NOT EXISTS (
    SELECT 1 FROM SKYPOINTS.DQ_REJECT d
    WHERE d.BATCH_ID = REDEMPTION_PARSED.BATCH_ID
      AND d.SOURCE_FILE = REDEMPTION_PARSED.SOURCE_FILE
      AND d.FEED_NAME = 'REDEMPTION'
      AND TO_JSON(d.RAW_RECORD) = TO_JSON(REDEMPTION_PARSED.RAW_TXN)
  );

CREATE OR REPLACE TEMP TABLE REDEMPTION_WINNERS AS
SELECT * FROM REDEMPTION_PARSED
WHERE MEMBER_ID IS NOT NULL AND TRIM(MEMBER_ID) <> '' AND FEED_DATE IS NOT NULL
  AND TXN_ID IS NOT NULL AND TRIM(TXN_ID) <> '' AND TXN_DATE IS NOT NULL
  AND PARTNER IS NOT NULL AND TRIM(PARTNER) <> ''
  AND MILES_REDEEMED IS NOT NULL AND MILES_REDEEMED > 0
  AND MILES_REDEEMED = TRUNC(MILES_REDEEMED)
  AND STATUS IN ('COMPLETED','PENDING','REJECTED','CANCELLED')
  AND FEED_DATE <= $AS_OF_DATE AND TXN_DATE <= FEED_DATE AND TXN_DATE <= $AS_OF_DATE
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY TXN_ID ORDER BY EFFECTIVE_AT DESC, SOURCE_FILE DESC
) = 1;

INSERT INTO SKYPOINTS.DQ_REJECT
  (BATCH_ID, FEED_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER, REASON_CODE, REASON_DETAIL, RAW_RECORD)
SELECT BATCH_ID, 'REDEMPTION', SOURCE_FILE, SOURCE_ROW_NUMBER,
       'DUPLICATE_TXN_SUPERSEDED', 'A later source transaction with this txn_id won the batch', RAW_TXN
FROM REDEMPTION_PARSED
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY TXN_ID ORDER BY EFFECTIVE_AT DESC, SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC
) > 1
  AND NOT EXISTS (
    SELECT 1 FROM SKYPOINTS.DQ_REJECT d
    WHERE d.BATCH_ID=REDEMPTION_PARSED.BATCH_ID
      AND d.SOURCE_FILE=REDEMPTION_PARSED.SOURCE_FILE
      AND d.SOURCE_ROW_NUMBER=REDEMPTION_PARSED.SOURCE_ROW_NUMBER
      AND d.FEED_NAME='REDEMPTION' AND d.REASON_CODE='DUPLICATE_TXN_SUPERSEDED'
  );

BEGIN TRANSACTION;

-- Stage insertion is replay-safe for one immutable batch/source row key.
INSERT INTO SKYPOINTS.MEMBER_STAGING
SELECT w.* FROM MEMBER_WINNERS w
WHERE NOT EXISTS (
  SELECT 1 FROM SKYPOINTS.MEMBER_STAGING s
  WHERE s.BATCH_ID=w.BATCH_ID AND s.SOURCE_FILE=w.SOURCE_FILE
    AND s.SOURCE_ROW_NUMBER=w.SOURCE_ROW_NUMBER
);

MERGE INTO SKYPOINTS.MEMBER_CURRENT t USING MEMBER_WINNERS s ON t.MEMBER_ID=s.MEMBER_ID
WHEN MATCHED AND s.SOURCE_UPDATED_AT > t.SOURCE_UPDATED_AT THEN UPDATE SET
  MEMBER_NAME=s.MEMBER_NAME, ENROLLMENT_DATE=s.ENROLLMENT_DATE, LAST_FLIGHT_DATE=s.LAST_FLIGHT_DATE,
  TIER_CODE=s.TIER_CODE, AGENT_NAME=s.AGENT_NAME, STATE=s.STATE, COUNTRY=s.COUNTRY,
  POSTCODE=s.POSTCODE, DOB=s.DOB, IS_ACTIVE=s.IS_ACTIVE, AGE=s.AGE, STALE_MEMBER=s.STALE_MEMBER,
  SOURCE_UPDATED_AT=s.SOURCE_UPDATED_AT, BATCH_ID=s.BATCH_ID
WHEN NOT MATCHED THEN INSERT
  (MEMBER_ID,MEMBER_NAME,ENROLLMENT_DATE,LAST_FLIGHT_DATE,TIER_CODE,AGENT_NAME,STATE,COUNTRY,
   POSTCODE,DOB,IS_ACTIVE,AGE,STALE_MEMBER,SOURCE_UPDATED_AT,BATCH_ID)
VALUES
  (s.MEMBER_ID,s.MEMBER_NAME,s.ENROLLMENT_DATE,s.LAST_FLIGHT_DATE,s.TIER_CODE,s.AGENT_NAME,s.STATE,
   s.COUNTRY,s.POSTCODE,s.DOB,s.IS_ACTIVE,s.AGE,s.STALE_MEMBER,s.SOURCE_UPDATED_AT,s.BATCH_ID);

-- Age and staleness change with time even without a new member profile feed.
UPDATE SKYPOINTS.MEMBER_CURRENT
SET AGE = IFF(DOB IS NULL, NULL, DATEDIFF(year, DOB, $AS_OF_DATE)
              - IFF(TO_CHAR($AS_OF_DATE,'MMDD') < TO_CHAR(DOB,'MMDD'), 1, 0)),
    STALE_MEMBER = COALESCE(DATEDIFF(day, LAST_FLIGHT_DATE, $AS_OF_DATE) > 90, FALSE);

-- Country serving tables are synchronized from canonical current state; moved members
-- are removed from their former country table in the same transaction.
MERGE INTO SKYPOINTS.MEMBER_INDIA t USING (SELECT * FROM SKYPOINTS.MEMBER_CURRENT WHERE COUNTRY='IND') s
ON t.MEMBER_ID=s.MEMBER_ID WHEN MATCHED THEN UPDATE ALL BY NAME WHEN NOT MATCHED THEN INSERT ALL BY NAME;
DELETE FROM SKYPOINTS.MEMBER_INDIA t WHERE NOT EXISTS
  (SELECT 1 FROM SKYPOINTS.MEMBER_CURRENT c WHERE c.MEMBER_ID=t.MEMBER_ID AND c.COUNTRY='IND');

MERGE INTO SKYPOINTS.MEMBER_USA t USING (SELECT * FROM SKYPOINTS.MEMBER_CURRENT WHERE COUNTRY='USA') s
ON t.MEMBER_ID=s.MEMBER_ID WHEN MATCHED THEN UPDATE ALL BY NAME WHEN NOT MATCHED THEN INSERT ALL BY NAME;
DELETE FROM SKYPOINTS.MEMBER_USA t WHERE NOT EXISTS
  (SELECT 1 FROM SKYPOINTS.MEMBER_CURRENT c WHERE c.MEMBER_ID=t.MEMBER_ID AND c.COUNTRY='USA');

MERGE INTO SKYPOINTS.MEMBER_AUS t USING (SELECT * FROM SKYPOINTS.MEMBER_CURRENT WHERE COUNTRY='AUS') s
ON t.MEMBER_ID=s.MEMBER_ID WHEN MATCHED THEN UPDATE ALL BY NAME WHEN NOT MATCHED THEN INSERT ALL BY NAME;
DELETE FROM SKYPOINTS.MEMBER_AUS t WHERE NOT EXISTS
  (SELECT 1 FROM SKYPOINTS.MEMBER_CURRENT c WHERE c.MEMBER_ID=t.MEMBER_ID AND c.COUNTRY='AUS');

MERGE INTO SKYPOINTS.REDEMPTION_TRANSACTION t USING REDEMPTION_WINNERS s ON t.TXN_ID=s.TXN_ID
WHEN MATCHED AND s.EFFECTIVE_AT > t.SOURCE_UPDATED_AT THEN UPDATE SET
  MEMBER_ID=s.MEMBER_ID, FEED_DATE=s.FEED_DATE, TXN_DATE=s.TXN_DATE, PARTNER=s.PARTNER,
  MILES_REDEEMED=s.MILES_REDEEMED, STATUS=s.STATUS, BATCH_ID=s.BATCH_ID,
  SOURCE_UPDATED_AT=s.EFFECTIVE_AT, INGESTED_AT=s.INGESTED_AT
WHEN NOT MATCHED THEN INSERT
  (TXN_ID,MEMBER_ID,FEED_DATE,TXN_DATE,PARTNER,MILES_REDEEMED,STATUS,BATCH_ID,SOURCE_UPDATED_AT,INGESTED_AT)
VALUES
  (s.TXN_ID,s.MEMBER_ID,s.FEED_DATE,s.TXN_DATE,s.PARTNER,s.MILES_REDEEMED,s.STATUS,
   s.BATCH_ID,s.EFFECTIVE_AT,s.INGESTED_AT);

UPDATE SKYPOINTS.ETL_BATCH_AUDIT
SET STATUS='COMPLETED', COMPLETED_AT=CURRENT_TIMESTAMP(),
    ROWS_ACCEPTED=(SELECT COUNT(*) FROM MEMBER_WINNERS)
                 +(SELECT COUNT(*) FROM REDEMPTION_WINNERS),
    ROWS_REJECTED=(SELECT COUNT(*) FROM SKYPOINTS.DQ_REJECT WHERE BATCH_ID=$BATCH_ID)
WHERE BATCH_ID=$BATCH_ID;

COMMIT;

-- Link transactions to current member country; preserve unmatched transactions for monitoring.
SELECT m.MEMBER_ID, m.COUNTRY, r.TXN_ID, r.TXN_DATE, r.MILES_REDEEMED, r.STATUS
FROM SKYPOINTS.REDEMPTION_TRANSACTION r
LEFT JOIN SKYPOINTS.MEMBER_CURRENT m USING (MEMBER_ID);
