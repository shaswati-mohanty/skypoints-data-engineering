-- Parse accepted source date variants; quarantine invalid dates before this transformation.
-- :AS_OF_DATE is the batch business date; stable for reproducibility and replay.
INSERT INTO SKYPOINTS.MEMBER_STAGING
SELECT MEMBER_ID, MEMBER_NAME, TRY_TO_DATE(ENROLLMENT_DATE_RAW, 'YYYYMMDD'),
       TRY_TO_DATE(LAST_FLIGHT_DATE_RAW, 'YYYYMMDD'), TIER_CODE, AGENT_NAME, STATE, COUNTRY,
       TRY_TO_NUMBER(POSTCODE_RAW), TRY_TO_DATE(DOB_RAW, 'MMDDYYYY'), IS_ACTIVE,
       IFF(DOB_RAW IS NULL, NULL, DATEDIFF(year, TRY_TO_DATE(DOB_RAW, 'MMDDYYYY'), :AS_OF_DATE)
         - IFF(TO_CHAR(:AS_OF_DATE, 'MMDD') < TO_CHAR(TRY_TO_DATE(DOB_RAW, 'MMDDYYYY'), 'MMDD'), 1, 0)),
       COALESCE(DATEDIFF(day, TRY_TO_DATE(LAST_FLIGHT_DATE_RAW, 'YYYYMMDD'), :AS_OF_DATE) > 90, FALSE),
       COALESCE(SOURCE_UPDATED_AT, INGESTED_AT), BATCH_ID, SOURCE_FILE, SOURCE_ROW_NUMBER
FROM SKYPOINTS.MEMBER_LANDING
WHERE BATCH_ID = :BATCH_ID
  AND RECORD_TYPE = 'D'
  -- Invalid mandatory dates must be written to DQ_REJECT before this insert.
  AND TRY_TO_DATE(ENROLLMENT_DATE_RAW, 'YYYYMMDD') IS NOT NULL;

-- Stage a deterministic winner: latest source timestamp, then batch/file/row tie-break.
CREATE OR REPLACE TEMP TABLE MEMBER_WINNERS AS
SELECT * FROM SKYPOINTS.MEMBER_STAGING
QUALIFY ROW_NUMBER() OVER (PARTITION BY MEMBER_ID ORDER BY SOURCE_UPDATED_AT DESC, BATCH_ID DESC, SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC) = 1;
MERGE INTO SKYPOINTS.MEMBER_CURRENT t USING MEMBER_WINNERS s ON t.MEMBER_ID=s.MEMBER_ID
WHEN MATCHED AND s.SOURCE_UPDATED_AT >= t.SOURCE_UPDATED_AT THEN UPDATE SET
  MEMBER_NAME=s.MEMBER_NAME, ENROLLMENT_DATE=s.ENROLLMENT_DATE, LAST_FLIGHT_DATE=s.LAST_FLIGHT_DATE,
  TIER_CODE=s.TIER_CODE, AGENT_NAME=s.AGENT_NAME, STATE=s.STATE, COUNTRY=s.COUNTRY, POSTCODE=s.POSTCODE,
  DOB=s.DOB, IS_ACTIVE=s.IS_ACTIVE, AGE=s.AGE, STALE_MEMBER=s.STALE_MEMBER,
  SOURCE_UPDATED_AT=s.SOURCE_UPDATED_AT, BATCH_ID=s.BATCH_ID
WHEN NOT MATCHED THEN INSERT (MEMBER_ID,MEMBER_NAME,ENROLLMENT_DATE,LAST_FLIGHT_DATE,TIER_CODE,AGENT_NAME,STATE,COUNTRY,POSTCODE,DOB,IS_ACTIVE,AGE,STALE_MEMBER,SOURCE_UPDATED_AT,BATCH_ID)
VALUES (s.MEMBER_ID,s.MEMBER_NAME,s.ENROLLMENT_DATE,s.LAST_FLIGHT_DATE,s.TIER_CODE,s.AGENT_NAME,s.STATE,s.COUNTRY,s.POSTCODE,s.DOB,s.IS_ACTIVE,s.AGE,s.STALE_MEMBER,s.SOURCE_UPDATED_AT,s.BATCH_ID);
-- Dynamic country routing should be orchestrated by country allow-list and use bound values.
MERGE INTO SKYPOINTS.MEMBER_INDIA t USING (SELECT * FROM SKYPOINTS.MEMBER_CURRENT WHERE COUNTRY='IND') s ON t.MEMBER_ID=s.MEMBER_ID
WHEN MATCHED THEN UPDATE ALL BY NAME WHEN NOT MATCHED THEN INSERT ALL BY NAME;
-- Keep this target synchronized with the latest global member state. This also removes
-- members who moved countries and rows no longer present in the current state table.
DELETE FROM SKYPOINTS.MEMBER_INDIA t
WHERE NOT EXISTS (
  SELECT 1 FROM SKYPOINTS.MEMBER_CURRENT c
  WHERE c.MEMBER_ID = t.MEMBER_ID AND c.COUNTRY = 'IND'
);

-- FLATTEN one row per redemption. Deduplicate transaction IDs with deterministic ingestion ordering.
INSERT INTO SKYPOINTS.REDEMPTION_TRANSACTION
SELECT txn.value:txn_id::VARCHAR, payload.value:member_id::VARCHAR,
       TRY_TO_DATE(payload.value:feed_date::VARCHAR, 'YYYYMMDD'),
       TRY_TO_DATE(txn.value:txn_date::VARCHAR, 'YYYYMMDD'), txn.value:partner::VARCHAR,
       txn.value:miles_redeemed::NUMBER(18,0), UPPER(txn.value:status::VARCHAR), l.BATCH_ID, l.INGESTED_AT
FROM SKYPOINTS.REDEMPTION_LANDING l, LATERAL FLATTEN(input=>l.RAW_PAYLOAD) payload,
     LATERAL FLATTEN(input=>payload.value:redemptions) txn
WHERE l.BATCH_ID=:BATCH_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY txn.value:txn_id::VARCHAR ORDER BY l.INGESTED_AT DESC, l.BATCH_ID DESC)=1;
-- Join by stable member_id; unmatched transactions are retained for a DQ/orphan-member report.
SELECT m.MEMBER_ID, m.COUNTRY, r.TXN_ID, r.TXN_DATE, r.MILES_REDEEMED, r.STATUS
FROM SKYPOINTS.REDEMPTION_TRANSACTION r LEFT JOIN SKYPOINTS.MEMBER_CURRENT m USING (MEMBER_ID);
