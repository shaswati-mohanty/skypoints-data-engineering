-- Production bulk-load template for normalized country CSVs.
-- Upload the COUNTRY_members_YYYYMMDD.csv files produced by the Python CLI to this named stage
-- through Snowsight or an approved cloud-storage integration before running COPY INTO.
-- Set BATCH_ID to the content hash emitted in ingestion_manifest_YYYYMMDD.json.
SET BATCH_ID = 'REPLACE_WITH_CONTENT_HASH';

CREATE FILE FORMAT IF NOT EXISTS SKYPOINTS.MEMBER_CSV_FORMAT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  TRIM_SPACE = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS SKYPOINTS.MEMBER_INPUT_STAGE
  FILE_FORMAT = (FORMAT_NAME = 'SKYPOINTS.MEMBER_CSV_FORMAT');

CREATE TABLE IF NOT EXISTS SKYPOINTS.MEMBER_BULK_LANDING (
  BATCH_ID VARCHAR NOT NULL,
  COUNTRY_CODE VARCHAR(3) NOT NULL,
  SOURCE_FILE VARCHAR NOT NULL,
  SOURCE_ROW_NUMBER NUMBER NOT NULL,
  INGEST_DATE DATE NOT NULL,
  INGESTED_AT TIMESTAMP_NTZ NOT NULL,
  RAW_RECORD VARIANT NOT NULL,
  NORMALIZED_RECORD VARIANT NOT NULL
)
CLUSTER BY (BATCH_ID, COUNTRY_CODE, INGEST_DATE);

-- COPY INTO uses Snowflake's bulk loader rather than one generated SQL expression per input row.
-- The output CSV order is the canonical seven-column schema documented in README.md.
COPY INTO SKYPOINTS.MEMBER_BULK_LANDING
  (BATCH_ID, COUNTRY_CODE, SOURCE_FILE, SOURCE_ROW_NUMBER, INGEST_DATE, INGESTED_AT,
   RAW_RECORD, NORMALIZED_RECORD)
FROM (
  SELECT
    $BATCH_ID,
    REGEXP_SUBSTR(METADATA$FILENAME,
      '(^|/)(USA|IND|AUS)_members_[0-9]{8}[.]csv$', 1, 1, 'e', 2),
    METADATA$FILENAME,
    METADATA$FILE_ROW_NUMBER,
    CURRENT_DATE(),
    CURRENT_TIMESTAMP(),
    OBJECT_CONSTRUCT_KEEP_NULL(
      'ID', $1, 'MEMBER_NAME', $2, 'DOB', $3, 'TIER_CODE', $4,
      'ENROLLMENT_DATE', $5, 'IND_CORP', $6, 'FLIGHT_DATE', $7
    ),
    OBJECT_CONSTRUCT_KEEP_NULL(
      'ID', $1, 'MEMBER_NAME', $2, 'DOB', $3, 'TIER_CODE', $4,
      'ENROLLMENT_DATE', $5, 'IND_CORP', $6, 'FLIGHT_DATE', $7
    )
  FROM @SKYPOINTS.MEMBER_INPUT_STAGE
)
FILE_FORMAT = (FORMAT_NAME = SKYPOINTS.MEMBER_CSV_FORMAT)
PATTERN = '.*(USA|IND|AUS)_members_[0-9]{8}[.]csv'
ON_ERROR = 'ABORT_STATEMENT';

-- Reconcile the stage-load result with manifest totals before the MERGE into serving tables.
-- Persist COPY_HISTORY/VALIDATE results into DQ_REJECT in the orchestrator when a load fails.
SELECT * FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME => 'MEMBER_BULK_LANDING',
  START_TIME => DATEADD('hour', -2, CURRENT_TIMESTAMP())
)) ORDER BY LAST_LOAD_TIME DESC;
