CREATE TABLE IF NOT EXISTS MEMBER_LANDING (
 BATCH_ID VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL, SOURCE_ROW_NUMBER NUMBER NOT NULL,
 INGESTED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(), RAW_RECORD VARIANT NOT NULL,
 RECORD_TYPE VARCHAR, MEMBER_NAME VARCHAR, MEMBER_ID VARCHAR, ENROLLMENT_DATE_RAW VARCHAR,
 LAST_FLIGHT_DATE_RAW VARCHAR, TIER_CODE VARCHAR, AGENT_NAME VARCHAR, STATE VARCHAR, COUNTRY VARCHAR,
 POSTCODE_RAW VARCHAR, DOB_RAW VARCHAR, IS_ACTIVE VARCHAR,
 CONSTRAINT PK_MEMBER_LANDING PRIMARY KEY(BATCH_ID,SOURCE_FILE,SOURCE_ROW_NUMBER) NOT ENFORCED
);
CREATE TABLE IF NOT EXISTS MEMBER_STAGING (
 MEMBER_ID VARCHAR(18) NOT NULL, MEMBER_NAME VARCHAR(255) NOT NULL, ENROLLMENT_DATE DATE NOT NULL,
 LAST_FLIGHT_DATE DATE, TIER_CODE CHAR(5), AGENT_NAME VARCHAR(255), STATE CHAR(5), COUNTRY CHAR(5) NOT NULL,
 POSTCODE NUMBER(5,0), DOB DATE, IS_ACTIVE CHAR(1), AGE NUMBER(3,0), STALE_MEMBER BOOLEAN NOT NULL,
 SOURCE_UPDATED_AT TIMESTAMP_NTZ NOT NULL, BATCH_ID VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL,
 SOURCE_ROW_NUMBER NUMBER NOT NULL
);
CREATE TABLE IF NOT EXISTS MEMBER_CURRENT (
 MEMBER_ID VARCHAR(18) NOT NULL, MEMBER_NAME VARCHAR(255) NOT NULL, ENROLLMENT_DATE DATE NOT NULL,
 LAST_FLIGHT_DATE DATE, TIER_CODE CHAR(5), AGENT_NAME VARCHAR(255), STATE CHAR(5), COUNTRY CHAR(5) NOT NULL,
 POSTCODE NUMBER(5,0), DOB DATE, IS_ACTIVE CHAR(1), AGE NUMBER(3,0), STALE_MEMBER BOOLEAN NOT NULL,
 SOURCE_UPDATED_AT TIMESTAMP_NTZ NOT NULL, BATCH_ID VARCHAR NOT NULL
);
CREATE TABLE IF NOT EXISTS REDEMPTION_LANDING (
 BATCH_ID VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL,
 INGESTED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(), RAW_PAYLOAD VARIANT NOT NULL
);
CREATE TABLE IF NOT EXISTS REDEMPTION_TRANSACTION (
 TXN_ID VARCHAR NOT NULL, MEMBER_ID VARCHAR(18) NOT NULL, FEED_DATE DATE NOT NULL,
 TXN_DATE DATE NOT NULL, PARTNER VARCHAR NOT NULL, MILES_REDEEMED NUMBER(18,0) NOT NULL,
 STATUS VARCHAR NOT NULL, BATCH_ID VARCHAR NOT NULL, INGESTED_AT TIMESTAMP_NTZ NOT NULL
);
