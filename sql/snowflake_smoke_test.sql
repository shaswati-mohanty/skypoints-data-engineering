INSERT INTO MEMBER_STAGING
SELECT MEMBER_ID,MEMBER_NAME,TRY_TO_DATE(ENROLLMENT_DATE_RAW,'YYYYMMDD'),
 TRY_TO_DATE(LAST_FLIGHT_DATE_RAW,'YYYYMMDD'),TIER_CODE,AGENT_NAME,STATE,COUNTRY,TRY_TO_NUMBER(POSTCODE_RAW),
 TRY_TO_DATE(DOB_RAW,'MMDDYYYY'),IS_ACTIVE,
 IFF(TRY_TO_DATE(DOB_RAW,'MMDDYYYY') IS NULL,NULL,DATEDIFF(year,TRY_TO_DATE(DOB_RAW,'MMDDYYYY'),TO_DATE($AS_OF_DATE))
  - IFF(TO_CHAR(TO_DATE($AS_OF_DATE),'MMDD')<TO_CHAR(TRY_TO_DATE(DOB_RAW,'MMDDYYYY'),'MMDD'),1,0)),
 COALESCE(DATEDIFF(day,TRY_TO_DATE(LAST_FLIGHT_DATE_RAW,'YYYYMMDD'),TO_DATE($AS_OF_DATE))>90,FALSE),
 INGESTED_AT,BATCH_ID,SOURCE_FILE,SOURCE_ROW_NUMBER
FROM MEMBER_LANDING WHERE BATCH_ID=$BATCH_ID AND RECORD_TYPE='D';

CREATE OR REPLACE TEMP TABLE MEMBER_WINNERS AS
SELECT * FROM MEMBER_STAGING WHERE BATCH_ID=$BATCH_ID
QUALIFY ROW_NUMBER() OVER(PARTITION BY MEMBER_ID ORDER BY SOURCE_UPDATED_AT DESC,BATCH_ID DESC,SOURCE_FILE DESC,SOURCE_ROW_NUMBER DESC)=1;
MERGE INTO MEMBER_CURRENT t USING MEMBER_WINNERS s ON t.MEMBER_ID=s.MEMBER_ID
WHEN MATCHED AND s.SOURCE_UPDATED_AT>=t.SOURCE_UPDATED_AT THEN UPDATE SET
 MEMBER_NAME=s.MEMBER_NAME,ENROLLMENT_DATE=s.ENROLLMENT_DATE,LAST_FLIGHT_DATE=s.LAST_FLIGHT_DATE,
 TIER_CODE=s.TIER_CODE,AGENT_NAME=s.AGENT_NAME,STATE=s.STATE,COUNTRY=s.COUNTRY,POSTCODE=s.POSTCODE,
 DOB=s.DOB,IS_ACTIVE=s.IS_ACTIVE,AGE=s.AGE,STALE_MEMBER=s.STALE_MEMBER,SOURCE_UPDATED_AT=s.SOURCE_UPDATED_AT,BATCH_ID=s.BATCH_ID
WHEN NOT MATCHED THEN INSERT(MEMBER_ID,MEMBER_NAME,ENROLLMENT_DATE,LAST_FLIGHT_DATE,TIER_CODE,AGENT_NAME,STATE,COUNTRY,POSTCODE,DOB,IS_ACTIVE,AGE,STALE_MEMBER,SOURCE_UPDATED_AT,BATCH_ID)
VALUES(s.MEMBER_ID,s.MEMBER_NAME,s.ENROLLMENT_DATE,s.LAST_FLIGHT_DATE,s.TIER_CODE,s.AGENT_NAME,s.STATE,s.COUNTRY,s.POSTCODE,s.DOB,s.IS_ACTIVE,s.AGE,s.STALE_MEMBER,s.SOURCE_UPDATED_AT,s.BATCH_ID);
MERGE INTO MEMBER_INDIA t USING (SELECT * FROM MEMBER_CURRENT WHERE COUNTRY='IND' AND MEMBER_ID='TST000000000001') s
ON t.MEMBER_ID=s.MEMBER_ID WHEN MATCHED THEN UPDATE ALL BY NAME WHEN NOT MATCHED THEN INSERT ALL BY NAME;
DELETE FROM MEMBER_INDIA WHERE MEMBER_ID='TST000000000001' AND MEMBER_ID IN (SELECT MEMBER_ID FROM MEMBER_CURRENT WHERE COUNTRY<>'IND');

INSERT INTO REDEMPTION_TRANSACTION(TXN_ID,MEMBER_ID,FEED_DATE,TXN_DATE,PARTNER,MILES_REDEEMED,STATUS,BATCH_ID,INGESTED_AT)
SELECT txn.value:txn_id::VARCHAR,payload.value:member_id::VARCHAR,TRY_TO_DATE(payload.value:feed_date::VARCHAR,'YYYYMMDD'),
 TRY_TO_DATE(txn.value:txn_date::VARCHAR,'YYYYMMDD'),txn.value:partner::VARCHAR,txn.value:miles_redeemed::NUMBER(18,0),
 UPPER(txn.value:status::VARCHAR),l.BATCH_ID,l.INGESTED_AT
FROM REDEMPTION_LANDING l,LATERAL FLATTEN(input=>ARRAY_CONSTRUCT(l.RAW_PAYLOAD)) payload,
 LATERAL FLATTEN(input=>payload.value:redemptions) txn WHERE l.BATCH_ID=$BATCH_ID;

